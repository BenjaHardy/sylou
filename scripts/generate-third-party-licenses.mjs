#!/usr/bin/env node
// Generates THIRD_PARTY_LICENSES.md from package-lock.json (single source of
// truth: the lockfile's per-package `license` metadata — no node_modules
// needed, no extra dependencies, fully reproducible).
//
// Usage:
//   node scripts/generate-third-party-licenses.mjs          # (re)write the file
//   node scripts/generate-third-party-licenses.mjs --check  # exit 1 if stale
//
// CI runs --check so any dependency change must regenerate the file in the
// same PR. The check compares content, it never writes.
//
// The edge-function externals (imported by URL in supabase/functions/, so
// invisible to the lockfile) are maintained in EDGE_DEPS below — update it
// when an edge function gains or drops an external import.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_PATH = join(root, "THIRD_PARTY_LICENSES.md");

const EDGE_DEPS = [
  { name: "@supabase/supabase-js", version: "2.110.5", license: "MIT", via: "esm.sh (all edge functions)" },
  { name: "mammoth", version: "1.12.3", license: "BSD-2-Clause", via: "npm: specifier (extract-text)" },
  { name: "unpdf", version: "1.9.1", license: "MIT", via: "npm: specifier (extract-text)" },
  { name: "PDF.js", version: "6.4.299", license: "Apache-2.0", via: "unpdf's bundle (extract-text)" },
  { name: "jszip", version: "3.10.2", license: "(MIT OR GPL-3.0-or-later)", via: "npm: specifier (edge-function tests only)" },
  { name: "Deno standard library (std)", version: "0.224.0", license: "MIT", via: "deno.land (edge-function tests only)" },
];

const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));

// Collect name@version → { license, dev } from the lockfile's package entries.
// Nested paths ("node_modules/a/node_modules/b") name the innermost package.
const seen = new Map();
for (const [path, info] of Object.entries(lock.packages ?? {})) {
  if (!path.startsWith("node_modules/")) continue; // skip the root project entry
  const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
  const key = `${name}@${info.version ?? "?"}`;
  const license = info.license ?? "UNKNOWN";
  const dev = info.dev === true;
  const prev = seen.get(key);
  // A package that appears anywhere as a runtime dep counts as runtime.
  if (!prev || (prev.dev && !dev)) seen.set(key, { name, version: info.version ?? "?", license, dev });
}

function grouped(entries) {
  const byLicense = new Map();
  for (const e of entries) {
    if (!byLicense.has(e.license)) byLicense.set(e.license, []);
    byLicense.get(e.license).push(`${e.name}@${e.version}`);
  }
  return [...byLicense.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([license, pkgs]) => ({ license, pkgs: pkgs.sort((a, b) => a.localeCompare(b)) }));
}

const all = [...seen.values()];
const runtime = grouped(all.filter((e) => !e.dev));
const dev = grouped(all.filter((e) => e.dev));

function section(groups) {
  return groups
    .map(
      ({ license, pkgs }) =>
        `### ${license} (${pkgs.length})\n\n${pkgs.map((p) => `- ${p}`).join("\n")}\n`,
    )
    .join("\n");
}

const content = `# Third-party licenses

Sylou's own code is licensed under AGPL-3.0-only and the FLOW methodology
under CC BY-SA 4.0 (see [LICENSING.md](LICENSING.md)). This file lists the
third-party open-source packages Sylou depends on, grouped by license.

Generated by \`scripts/generate-third-party-licenses.mjs\` from
\`package-lock.json\` (exact pinned versions). Do not edit by hand — CI
verifies this file matches the lockfile. Each package's full license text
and copyright notice ships inside the package itself (\`node_modules/<name>/\`
after \`npm ci\`).

## Edge-function dependencies (imported by URL)

${EDGE_DEPS.map((d) => `- ${d.name}@${d.version} — ${d.license} — via ${d.via}`).join("\n")}

## Runtime dependencies (npm)

Packages bundled into (or supporting) the shipped application.

${section(runtime)}
## Development toolchain (npm, not distributed)

Build, test and lint tooling used to develop Sylou; these packages are not
part of the shipped application.

${section(dev)}`;

if (process.argv.includes("--check")) {
  let existing = "";
  try {
    // Git on Windows checks the file out with CRLF line endings (core.autocrlf);
    // the comparison is about content, not line endings.
    existing = readFileSync(OUT_PATH, "utf8").replace(/\r\n/g, "\n");
  } catch {
    console.error("THIRD_PARTY_LICENSES.md is missing. Run: node scripts/generate-third-party-licenses.mjs");
    process.exit(1);
  }
  if (existing !== content) {
    console.error(
      "THIRD_PARTY_LICENSES.md is out of date with package-lock.json. " +
        "Run: node scripts/generate-third-party-licenses.mjs",
    );
    process.exit(1);
  }
  console.log("THIRD_PARTY_LICENSES.md is up to date.");
} else {
  writeFileSync(OUT_PATH, content);
  const unknown = all.filter((e) => e.license === "UNKNOWN");
  console.log(
    `Wrote THIRD_PARTY_LICENSES.md: ${runtime.reduce((s, g) => s + g.pkgs.length, 0)} runtime, ` +
      `${dev.reduce((s, g) => s + g.pkgs.length, 0)} dev packages` +
      (unknown.length ? ` — WARNING: ${unknown.length} with UNKNOWN license` : ""),
  );
}
