// Behaviour pins for the public shared-report page, rendered from a fixture
// RPC row as an anonymous visitor sees it: the Report ID banner, band labels
// without raw scores, the generator stamp, the AI-generation head markers,
// the frozen writing snapshot and its provenance overlay, the Replay tab
// gated by the owner's share toggle, and the unknown-token state.
import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { MemoryRouter, Route, Routes } from "react-router-dom";
import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";

const { rows } = vi.hoisted(() => ({
  rows: { report: null as Record<string, unknown> | null, provenance: null as unknown[] | null },
}));

// The page reads the report through the token-gated RPC, column sets apart:
// the row, then the provenance map, then (on demand) the replay.
vi.mock("@/integrations/supabase/client", () => ({
  supabase: {
    rpc: () => ({
      select: (columns: string) => ({
        maybeSingle: async () => {
          if (columns === "provenance_snapshot") {
            return { data: rows.report ? { provenance_snapshot: rows.provenance } : null, error: null };
          }
          if (columns === "replay_snapshot") return { data: { replay_snapshot: null }, error: null };
          return { data: rows.report, error: null };
        },
      }),
    }),
  },
}));
vi.mock("@/components/flow-report/FlowPledgeBadge", () => ({ FlowPledgeBadge: () => null }));

import SharedReport from "@/pages/SharedReport";
import { getBandLabel } from "@/lib/flowBands";

const SCORES = { find: 3.7, lead: 2.2, organize: 4.1, write: 1.3 };
const pillar = (score: number, reasoning: string) => ({ score, reasoning, evidence: [], narrative: "" });

function makeRow(over: Record<string, unknown> = {}) {
  return {
    id: "r-1",
    project_id: "p-1",
    project_name: "Shared project",
    certificate_id: "FLOW-SHARED01",
    share_token: "tok-1",
    share_enabled: true,
    share_visibility: "public",
    share_include_feedback: false,
    share_include_replay: false,
    share_include_report: true,
    share_include_profile: true,
    model_used: "claude-sonnet-5-5",
    created_at: "2026-10-13T10:00:00.000Z",
    ai_find: pillar(SCORES.find, "Find reasoning."),
    ai_lead: pillar(SCORES.lead, "Lead reasoning."),
    ai_organize: pillar(SCORES.organize, "Organize reasoning."),
    ai_write: pillar(SCORES.write, "Write reasoning."),
    ai_summary: "Shared summary of the process.",
    key_user_contributions: [],
    flow_meta: null,
    metrics_snapshot: null,
    user_feedback_pre: null,
    user_feedback_post: null,
    writing_snapshot: "<p>Frozen text written</p>",
    generator_info: { instance_label: "official", instance_domain: "sylou.eu", version: "v0.7.0", commit_hash: "8ad03f5" },
    ...over,
  };
}

const FROZEN_SEGMENTS = [
  { start: 0, end: 8, source: "typed" },
  { start: 8, end: 12, source: "ai_editor" },
  { start: 12, end: 21, source: "typed" },
];

function renderPage(token = "tok-1") {
  return render(
    <MemoryRouter initialEntries={[`/report/${token}`]}>
      <Routes>
        <Route path="/report/:token" element={<SharedReport />} />
      </Routes>
    </MemoryRouter>,
  );
}

beforeAll(() => {
  vi.stubGlobal("ResizeObserver", class { observe() {} unobserve() {} disconnect() {} });
  window.scrollTo = vi.fn();
  Element.prototype.scrollTo = vi.fn();
});

beforeEach(() => {
  rows.report = makeRow();
  rows.provenance = FROZEN_SEGMENTS;
});

afterEach(() => {
  document.head.querySelectorAll("meta").forEach((m) => m.remove());
});

describe("SharedReport", () => {
  it("renders the report from the RPC row: banner, summary, band labels without raw scores, generator stamp", async () => {
    renderPage();

    expect(await screen.findByText("FLOW Report ID #FLOW-SHARED01")).toBeInTheDocument();
    expect(screen.getByText("Shared project")).toBeInTheDocument();
    expect(screen.getByText("Shared summary of the process.")).toBeInTheDocument();

    for (const score of Object.values(SCORES)) {
      expect(screen.getAllByText(getBandLabel(score)).length).toBeGreaterThan(0);
    }
    const text = document.body.textContent ?? "";
    for (const score of Object.values(SCORES)) {
      expect(text).not.toMatch(new RegExp(`\\b${String(score).replace(".", "\\.")}\\b`));
    }

    expect(text).toMatch(/Generated by Sylou \(official instance\) at sylou\.eu/);
    expect(text).toContain("v0.7.0");
    expect(text).toContain("8ad03f5");
    expect(text).toMatch(/Model: Claude Sonnet 5\.5/);
  });

  it("marks the page as AI-generated in the document head while the report is shown", async () => {
    const { unmount } = renderPage();
    await screen.findByText("FLOW Report ID #FLOW-SHARED01");

    await waitFor(() =>
      expect(document.head.querySelector('meta[name="ai-generated"]')).toHaveAttribute("content", "true"),
    );
    expect(document.head.querySelector('meta[name="ai-model"]')).toBeInTheDocument();

    unmount();
    expect(document.head.querySelector('meta[name="ai-generated"]')).not.toBeInTheDocument();
  });

  it("the Writing tab shows the frozen snapshot, and the highlighted view pairs it with the frozen provenance map", async () => {
    renderPage();
    await screen.findByText("FLOW Report ID #FLOW-SHARED01");

    fireEvent.click(screen.getByRole("button", { name: "Writing" }));
    expect(screen.getByText("Writing snapshot")).toBeInTheDocument();
    expect(screen.getByText("Frozen text written")).toBeInTheDocument();

    fireEvent.click(screen.getByRole("button", { name: "FLOW Report" }));
    fireEvent.click(await screen.findByRole("button", { name: "View Highlighted Text" }));
    const annotated = document.querySelector(".font-mono") as HTMLElement;
    expect(annotated.textContent).toBe("Frozen text written");
    const aiSpans = Array.from(annotated.querySelectorAll("span")).filter((s) => s.className.includes("bg-blue-200/60"));
    expect(aiSpans.map((s) => s.textContent).join("")).toBe("text");
  });

  it("offers the Replay tab only when the owner shared the replay", async () => {
    const first = renderPage();
    await screen.findByText("FLOW Report ID #FLOW-SHARED01");
    expect(screen.queryByRole("button", { name: /Replay/ })).not.toBeInTheDocument();
    first.unmount();

    rows.report = makeRow({ share_include_replay: true });
    renderPage();
    await screen.findByText("FLOW Report ID #FLOW-SHARED01");
    expect(screen.getByRole("button", { name: /Replay/ })).toBeInTheDocument();
  });

  it("an unknown or disabled token shows the unavailable notice, nothing else", async () => {
    rows.report = null;
    renderPage("nope");
    expect(await screen.findByText("Report not available")).toBeInTheDocument();
    expect(screen.queryByText(/FLOW Report ID/)).not.toBeInTheDocument();
  });
});
